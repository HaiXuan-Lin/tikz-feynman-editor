const reverse = Object.fromEntries(Object.entries(messages).map(([zh, en]) => [en, zh]))
export function translate(language, key, ...values) {
  const result =
    language === 'zh' ? chinese[key] || reverse[key] || key : messages[key] || key
  return result.replace(/\{(\d+)\}/g, (_, i) =>
    translate(language, String(values[Number(i)] ?? '')),
  )
}
